// ── Season data, generated ([seasons]) ─────────────────────────────────────
//
//   node scripts/syncSeasonData.mjs                 team table and rosters (reads ../Client/src/data/nflTeams.ts)
//   node scripts/syncSeasonData.mjs 2026            …and the bundled schedule for that year (from ESPN)
//   node scripts/syncSeasonData.mjs 2026 --careers  …and instead of the schedule, who is a rookie and who
//                                                   missed time last year (ESPN). A new season needs this once,
//                                                   then an entry in src/season/rosters.js.
//
// The rosters live on the client, and the two deploy from separate repositories. But the server simulates
// 272 games a season and gives out the league's awards, so it needs every club's conference, division,
// ratings and players. This copies those few fields across. RUN IT WHENEVER nflTeams.ts CHANGES.
//
// The bundled schedule is the fallback for when ESPN cannot be reached: a season can always start.
//
// The career data answers the two award questions no rating can: is this man a rookie (Offensive and
// Defensive Rookie of the Year), and did he miss time last season (Comeback Player of the Year). Players
// are matched to ESPN by name across the whole league, because a hand-kept roster can be a trade ahead
// of or behind the feed. ⚠️ THE SAME CLUB WINS A SHARED NAME: the league has two of some names, and one
// DeVonta Smith is a rookie. Anyone not found is simply not eligible for those awards.
//
// Needs Node 23.6 or newer, which runs nflTeams.ts directly.

import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { fetchSchedule } from '../src/season/schedule.js'

const here = dirname(fileURLToPath(import.meta.url))
const { NFL_TEAMS } = await import(pathToFileURL(resolve(here, '../../Client/src/data/nflTeams.ts')).href)
if (NFL_TEAMS.length !== 32) throw new Error(`expected 32 teams in nflTeams.ts, found ${NFL_TEAMS.length}`)

// ── The team table ───────────────────────────────────────────────────────

const rows = NFL_TEAMS.map(t => ({
  id: t.id, name: t.name, abbr: t.abbr, conference: t.conference, division: t.division,
  ovr: t.ovr, offOvr: t.offOvr, defOvr: t.defOvr,
}))

writeFileSync(
  resolve(here, '../src/season/teamData.js'),
  '// GENERATED by scripts/syncSeasonData.mjs from Client/src/data/nflTeams.ts. Do not edit by hand.\n' +
  'export const TEAM_DATA = [\n' +
  rows.map(r => '  ' + JSON.stringify(r) + ',').join('\n') +
  '\n]\n',
)
console.log('wrote teamData.js')

// ── The rosters: only what the box scores and the awards read ────────────

const KEEP = {
  QB: ['accuracy', 'speed'],
  RB: ['speed', 'vision', 'catching'],
  WR: ['speed', 'catching'],
  TE: ['speed', 'catching'],
  OL: ['passBlock', 'runBlock'],
  DL: ['passRush'],
  LB: ['awareness'],
  CB: ['awareness'],
  S: ['awareness'],
}

function compact(p) {
  const out = { id: p.id, name: p.name, pos: p.position, ovr: p.ovr }
  for (const key of KEEP[p.position] ?? []) out[key] = p.ratings?.[key] ?? p.ovr
  return out
}

const allPlayers = (t) => [t.qb, ...t.offense, ...(t.oline ?? []), ...t.defense, ...(t.dline ?? [])].filter(Boolean)

const lines = NFL_TEAMS.map(t => {
  const players = allPlayers(t).map(compact)
  return `  ${t.id}: [\n${players.map(p => '    ' + JSON.stringify(p)).join(',\n')},\n  ],`
})
writeFileSync(
  resolve(here, '../src/season/rosterData.js'),
  '// GENERATED by scripts/syncSeasonData.mjs from Client/src/data/nflTeams.ts. Do not edit by hand.\n' +
  `export const ROSTER_DATA = {\n${lines.join('\n')}\n}\n`,
)
console.log(`wrote rosterData.js — ${NFL_TEAMS.reduce((n, t) => n + allPlayers(t).length, 0)} players`)

// ── The schedule ─────────────────────────────────────────────────────────

const year = Number(process.argv.find(a => /^\d{4}$/.test(a)))
const dir = resolve(here, '../src/season/data')
mkdirSync(dir, { recursive: true })

if (year && !process.argv.includes('--careers')) {
  const schedule = await fetchSchedule(year)
  writeFileSync(
    resolve(dir, `schedule${year}.js`),
    `// GENERATED by scripts/syncSeasonData.mjs from ESPN's public NFL data. Do not edit by hand.\n` +
    `export default ${JSON.stringify(schedule)}\n`,
  )
  console.log(`wrote schedule${year}.js — ${schedule.games.length} games, SOS from ${schedule.sosYear}`)
}

// ── Careers ──────────────────────────────────────────────────────────────

const normalize = (name) => name.toLowerCase()
  .replace(/\b(jr|sr|ii|iii|iv|v)\b\.?/g, '')
  .replace(/[^a-z]/g, '')

async function getJson(url) {
  for (let attempt = 0; ; attempt++) {
    try {
      const res = await fetch(url, { headers: { accept: 'application/json' } })
      if (res.ok) return await res.json()
      if (res.status === 404) return null
      throw new Error(`HTTP ${res.status}`)
    } catch (err) {
      if (attempt >= 3) throw err
      await new Promise(r => setTimeout(r, 800 * (attempt + 1)))
    }
  }
}

// ESPN calls Washington WSH; the game calls it WAS. The rest agree.
const espnCode = (id) => (id === 'WAS' ? 'WSH' : id)

// A season can be split across rows when a player was traded, so a category's rows for a year add up.
// A lineman has no rows at all, which is why this only reports what it found.
function gamesIn(statsDoc, wanted) {
  let best = 0
  for (const cat of statsDoc?.categories ?? []) {
    const at = (cat.labels ?? []).indexOf('GP')
    if (at < 0) continue
    let n = 0
    for (const row of cat.statistics ?? []) {
      if (row.season?.year === wanted) n += Number(row.stats?.[at]) || 0
    }
    best = Math.max(best, n)
  }
  return best
}

async function inBatches(items, size, fn) {
  const out = []
  for (let i = 0; i < items.length; i += size) {
    out.push(...await Promise.all(items.slice(i, i + size).map(fn)))
  }
  return out
}

if (year && process.argv.includes('--careers')) {
  const league = new Map()
  for (const t of NFL_TEAMS) {
    const doc = await getJson(`https://site.api.espn.com/apis/site/v2/sports/football/nfl/teams/${espnCode(t.id)}/roster`)
    for (const group of doc?.athletes ?? []) {
      for (const a of group.items ?? []) {
        const key = normalize(a.fullName ?? a.displayName ?? '')
        const entry = { teamId: t.id, espnId: a.id, years: a.experience?.years ?? null }
        league.set(key, [...(league.get(key) ?? []), entry])
      }
    }
  }
  console.log(`${league.size} players on ESPN's rosters`)

  const rookies = []
  const veterans = []
  const missing = []
  for (const t of NFL_TEAMS) {
    for (const p of allPlayers(t)) {
      const named = league.get(normalize(p.name)) ?? []
      const found = named.find(e => e.teamId === t.id)
        ?? [...named].sort((a, b) => (b.years ?? 0) - (a.years ?? 0))[0]
      if (!found) { missing.push(`${t.id} ${p.name}`); continue }
      if (found.years === 0) rookies.push(p.id)
      else if (p.position !== 'OL') veterans.push({ id: p.id, espnId: found.espnId })
    }
  }

  const prevGames = {}
  await inBatches(veterans, 8, async ({ id, espnId }) => {
    const doc = await getJson(`https://site.web.api.espn.com/apis/common/v3/sports/football/nfl/athletes/${espnId}/stats`).catch(() => null)
    if (doc) prevGames[id] = gamesIn(doc, year - 1)
  })

  writeFileSync(
    resolve(dir, `careers${year}.js`),
    `// GENERATED by scripts/syncSeasonData.mjs from ESPN's public NFL data. Do not edit by hand.\n` +
    `// rookies: first-year players. prevGames: games played in ${year - 1}, for Comeback Player of the Year.\n` +
    `export default ${JSON.stringify({ year, rookies, prevGames })}\n`,
  )
  console.log(`wrote careers${year}.js — ${rookies.length} rookies, ${Object.keys(prevGames).length} veterans' ${year - 1} games`)
  if (missing.length) console.log(`not found on ESPN (no rookie or comeback eligibility): ${missing.length}\n  ${missing.join('; ')}`)
}
