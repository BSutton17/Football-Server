// ── Season data, generated ([seasons]) ─────────────────────────────────────
//
//   node scripts/syncSeasonData.mjs            team table only (reads ../Client/src/data/nflTeams.ts)
//   node scripts/syncSeasonData.mjs 2026       …and the bundled schedule for that year (from ESPN)
//
// The server has no rosters: they live on the client, and the two deploy from separate repositories.
// But it simulates 272 games a season and needs each team's conference, division and ratings to do
// that, so this copies those few fields across. Run it whenever the ratings in nflTeams.ts change.
//
// The bundled schedule is the fallback for when ESPN cannot be reached: a season can always start.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { fetchSchedule } from '../src/season/schedule.js'

const here = dirname(fileURLToPath(import.meta.url))
const source = readFileSync(resolve(here, '../../Client/src/data/nflTeams.ts'), 'utf8')

const rows = [...source.matchAll(
  /id: '([A-Z]+)', name: '([^']+)', abbr: '([A-Z]+)', conference: '(AFC|NFC)', division: '(\w+)'[^\n]*\n\s*ovr: (\d+), offOvr: (\d+), defOvr: (\d+)/g,
)].map(m => ({
  id: m[1], name: m[2], abbr: m[3], conference: m[4], division: m[5],
  ovr: Number(m[6]), offOvr: Number(m[7]), defOvr: Number(m[8]),
}))
if (rows.length !== 32) throw new Error(`expected 32 teams in nflTeams.ts, found ${rows.length}`)

writeFileSync(
  resolve(here, '../src/season/teamData.js'),
  '// GENERATED by scripts/syncSeasonData.mjs from Client/src/data/nflTeams.ts. Do not edit by hand.\n' +
  'export const TEAM_DATA = [\n' +
  rows.map(r => '  ' + JSON.stringify(r) + ',').join('\n') +
  '\n]\n',
)
console.log('wrote teamData.js')

const year = Number(process.argv[2])
if (year) {
  const schedule = await fetchSchedule(year)
  const dir = resolve(here, '../src/season/data')
  mkdirSync(dir, { recursive: true })
  writeFileSync(
    resolve(dir, `schedule${year}.js`),
    `// GENERATED by scripts/syncSeasonData.mjs from ESPN's public NFL data. Do not edit by hand.\n` +
    `export default ${JSON.stringify(schedule)}\n`,
  )
  console.log(`wrote schedule${year}.js — ${schedule.games.length} games, SOS from ${schedule.sosYear}`)
}
